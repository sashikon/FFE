// Детектор «ИИ-слопа» в русском тексте. Код только находит шаблоны — переписывает их модель,
// чтобы не ломать грамматику механическим вырезанием слов. Невидимые символы удаляются кодом.

// Пробелы нулевой ширины, мягкий перенос, метки направления текста, BOM
const INVISIBLE = /[­᠎​-‏‪-‮⁠-⁤⁦-⁩﻿]/g;

const cleanInvisible = (text) => text.replace(INVISIBLE, '').replace(/[ \t]+\n/g, '\n');

// \b в JS не работает с кириллицей — границы слова через Unicode-классы
const w = (src) => new RegExp(`(?<![\\p{L}\\p{N}])(?:${src})(?![\\p{L}\\p{N}])`, 'giu');
// Шаблонное начало предложения: после начала текста, точки, ! ? или переноса строки
const opener = (src) => new RegExp(`(?:^|[.!?…]\\s+|\\n\\s*)(?:${src})(?![\\p{L}])`, 'gimu');

const PATTERNS = [
  // Пустые конструкции
  ['пустая конструкция', w('в своей основе|по своей сути|в (?:нашем |современном |сегодняшнем )?(?:быстро меняющемся )?мире|в мире моды|в наше время|в эпоху,? когда|в современных реалиях|не секрет,? что|ни для кого не секрет|важно (?:отметить|понимать|подчеркнуть)|стоит (?:отметить|подчеркнуть|упомянуть|задуматься)|следует отметить|нельзя не отметить|играет (?:ключевую|важную|огромную|решающую) роль|является неотъемлемой частью|открывает новые горизонты|бросает вызов|на пересечении|в этом контексте|заставляет задуматься|давайте разберёмся|давайте разберемся|погрузимся|подводя итог')],
  // Шаблонные начала предложений
  ['шаблонное начало', opener('Более того|Кроме того|В конечном (?:счёте|счете|итоге)|По сути|В итоге|Таким образом|Итак|Примечательно,? что|Интересно,? что|Стоит отметить|Важно понимать|Однако важно|Именно поэтому|Вот почему|Странность в том|Парадокс в том|Получается парадокс|В этом вся механика|Отсюда (?:и )?(?:неудобный )?вывод')],
  // Заполнители и пустые усилители
  ['заполнитель', w('действительно|по сути|по-настоящему|поистине|невероятн\\p{L}*|абсолютно|совершенно|крайне|уникальн\\p{L}*|ключев(?:ой|ая|ое|ые|ую|ых|ым|ыми|ого|ому)')],
  // Абсолютные обобщения
  ['обобщение', w('всегда|никогда|никто не|каждый из нас|все мы|любой из нас')],
  // «Это не X. Это Y» / «Это не X — это Y»
  ['«Это не X. Это Y»', /(?<![\p{L}])Это не [^.!?\n,]{1,80}?(?:\.\s+|\s+[—–-]\s+)(?=это\s)/gimu],
];

const ANTITHESIS = /не (?:просто |только )?[^,.!?\n]{1,50}, а /giu;

// Список найденных мест: [{ kind, match }]
function findSlop(text) {
  const plain = text.replace(/<[^>]+>/g, '');
  const hits = [];
  const taken = []; // [start, end] уже найденных мест — вложенные совпадения не дублируем
  for (const [kind, re] of PATTERNS) {
    for (const m of plain.matchAll(re)) {
      const lead = m[0].length - m[0].replace(/^[.!?…\s]+/, '').length;
      const start = m.index + lead;
      const end = m.index + m[0].length;
      if (taken.some(([a, b]) => start < b && end > a)) continue;
      taken.push([start, end]);
      hits.push({ kind, match: plain.slice(start, end).trim() });
    }
  }
  const antitheses = [...plain.matchAll(ANTITHESIS)];
  if (antitheses.length > 1) {
    antitheses.slice(1).forEach((m) => hits.push({ kind: 'лишняя антитеза «не X, а Y»', match: m[0].trim() }));
  }
  return hits;
}

const describeSlop = (hits) => hits.map((h) => `«${h.match}» — ${h.kind}`).join('\n');

module.exports = { cleanInvisible, findSlop, describeSlop };

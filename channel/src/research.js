// Справка из веба перед разбором: откуда вещь или приём взялись. Без неё модель либо
// молчит об истоках, либо рискует их придумать — а выдуманная дата хуже её отсутствия.
const { callWithSearch, MODELS } = require('./llm');

const ENABLED = (process.env.WEB_RESEARCH || '').toLowerCase() !== 'off';
const MAX_SEARCHES = Number(process.env.WEB_RESEARCH_SEARCHES || 4);

const SYSTEM = `Ты собираешь фактическую справку для разбора моды. Тебе дают заголовки свежих заметок об одном сюжете. Найди в вебе происхождение вещи, детали или приёма, о которых идёт речь:
- где и когда они появились впервые (вещь, крой, деталь, слово);
- кто ввёл их в моду: дом, дизайнер, субкультура, фильм, человек;
- когда и через что они стали массовыми; были ли прошлые волны возвращения;
- если это нынешняя волна — с чьего показа или коллекции она началась.

Правила:
- только проверяемое: то, что подтверждается найденными страницами. Ищи на английском и на языке страны происхождения;
- даты, имена и названия коллекций приводи так, как они в источниках; расходятся — скажи, что версии расходятся;
- не пересказывай сами заметки, которые тебе дали: нужна предыстория, а не новость;
- если надёжного ответа нет, так и напиши: «надёжных сведений о происхождении не нашлось». Это нормальный ответ, пустая справка лучше выдуманной.

Ответ — по-русски, 5–10 коротких пунктов, без вступления.`;

async function researchOrigin(items) {
  if (!ENABLED || !items.length) return null;
  const notes = items.slice(0, 6).map((it, i) => `[${i + 1}] ${it.title}`).join('\n');
  const { text, sources, searches } = await callWithSearch({
    model: MODELS.smart,
    system: SYSTEM,
    user: `Заметки сюжета:\n\n${notes}\n\nСобери справку о происхождении того, о чём эти заметки.`,
    maxSearches: MAX_SEARCHES,
  });
  console.log(`[research] поисков ${searches}, источников ${sources.length}`);
  return text.trim() ? { text: text.trim(), sources } : null;
}

module.exports = { researchOrigin, ENABLED };

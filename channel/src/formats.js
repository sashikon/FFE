const PUBLISH_HOURS = (process.env.PUBLISH_HOURS || '10,19').split(',').map(Number).sort((a, b) => a - b);
const TZ = process.env.TZ || 'Europe/Moscow';

function localParts(date) {
  const parts = new Intl.DateTimeFormat('en-GB', {
    timeZone: TZ, weekday: 'short', hour: 'numeric', hourCycle: 'h23', year: 'numeric', month: '2-digit', day: '2-digit',
  }).formatToParts(date);
  const get = (t) => parts.find((p) => p.type === t).value;
  const day = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'].indexOf(get('weekday')) + 1;
  const localDate = Date.UTC(Number(get('year')), Number(get('month')) - 1, Number(get('day')));
  const weeksSinceStart = Math.floor((localDate - Date.parse(CYCLE_START)) / (7 * 24 * 3600 * 1000));
  const week = (((weeksSinceStart % 2) + 2) % 2) + 1;
  return { day, week, hour: Number(get('hour')) };
}

const formatAt = (date) => {
  const { day, week } = localParts(date);
  return FORMATS.find((f) => f.week === week && f.day === day) || FORMATS[0];
};
const formatByKey = (key) => FORMATS.find((f) => f.key === key) || null;

// Формат сегодняшнего дня (для публикации)
const formatToday = (date = new Date()) => formatAt(date);

// Формат дня ближайшего слота публикации (для черновиков): вечером готовим уже завтрашний
function formatForNextSlot(date = new Date()) {
  const sameDay = PUBLISH_HOURS.some((h) => h > localParts(date).hour);
  return formatAt(sameDay ? date : new Date(date.getTime() + 24 * 3600 * 1000));
}


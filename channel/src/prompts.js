function formatBlock(format) {
  return `Формат поста: «${format.title}»
Суть: ${format.idea}
Возможный ход: ${format.structure}
Это один из возможных ходов, а не обязательный порядок частей. Если материал просит другого движения — иди за материалом; формат задаёт, о чём пост, а не по каким ступеням он идёт.${format.note ? `\n${format.note}` : ''}`;
}

function insightUser(items, recentTheses, format) {
  const notes = items.map((it, i) =>
    `[${i + 1}] ${it.source} (${it.layer})\n${it.title}${it.summary ? `\n${it.summary}` : ''}`
  ).join('\n\n');
  const memory = recentTheses.length
    ? recentTheses.map((t) => `- ${t}`).join('\n')
    : '(пока ничего)';
  return `${formatBlock(format)}\n\nРазбери сюжет так, чтобы из него вышел пост именно этого формата.\n\nЗаметки сюжета:\n\n${notes}\n\nНедавние тезисы канала:\n${memory}`;
}

// ─── Шаг 5: текст поста ──────────────────────────────────────────────────────

const STYLE_DIR = path.join(__dirname, '..', 'style');

const readExample = (f) => fs.readFileSync(path.join(STYLE_DIR, 'examples', f), 'utf8').trim();

function rulesBlock(rules) {
  return rules.length
    ? `\n\nУроки редактора — правила, выведенные из правок автора канала. Они важнее стайлгайда, если противоречат ему:\n${rules.map((r) => `- ${r.rule}`).join('\n')}`
    : '';
}

function writeSystem(format, rules = []) {
  const readStyle = (f) => fs.readFileSync(path.join(STYLE_DIR, f), 'utf8').replace(/<!--[\s\S]*?-->/g, '').trim();
  const guide = readStyle('guide.md');
  const examples = format.examples.filter((f) => fs.existsSync(path.join(STYLE_DIR, 'examples', f))).map(readExample);
  const exBlock = examples.length
    ? `\n\nОбразцы постов этого формата — ориентир по голосу, ритму, длине и построению (не по темам):\n\n${examples.map((e, i) => `<example ${i + 1}>\n${e}\n</example>`).join('\n\n')}`
    : '';
  const theorists = readStyle('theorists.md');
  return `Ты пишешь посты для авторского Telegram-канала о смыслах в моде.

${guide}${rulesBlock(rules)}

Справка о теоретиках (для вводных при первом упоминании):
${theorists}

${formatBlock(format)}${exBlock}

Заголовок — мысль или парадокс, но не ценой неправды: если деталь работает, нельзя писать, что она не работает, ради красоты фразы. Проверь заголовок на буквальную верность: ремешок с пряжкой застёгивается, даже если ничего не держит.

Если в разборе есть origin — расскажи, откуда вещь или приём взялись: где появились впервые, кто ввёл их в моду, когда стали массовыми. Это то, зачем читатель приходит; без этого пост остаётся рассуждением о сегодняшнем дне. Ничего не достраивай: чего нет в разборе, того не пиши.

Технические требования:
- Разметка Telegram HTML: только <b>, <i>, <blockquote>. Никаких других тегов, никакого Markdown.
- Не вставляй ссылки и не упоминай «источник» — ссылки добавятся автоматически.
- Не добавляй в конце подпись или слоган канала — он ставится автоматически.
- Выведи только текст поста, без пояснений до или после.`;
}

// Каналу вредит не повтор темы, а повтор приёма: одинаковый заход и одинаковая посадка
function recentShapeBlock(recent = []) {
  if (!recent.length) return '';
  const lines = recent.map((r) => `- начало: «${r.opening}» · конец: «${r.ending}»`).join('\n');
  return `\n\nПоследние посты канала начинались и кончались так:\n${lines}\n`
    + 'Сделай иначе: другой заход в первых двух строках и другая посадка в последних. '
    + 'Кончать формулой или вопросом читателю — не обязанность: пост может закончиться наблюдением, сценой, самой вещью.';
}

function writeUser(insight, previous, recent = []) {
  let msg = `Разбор сюжета — это материал, а не план. Не раскладывай его поля по абзацам в том же порядке; строй пост по формату дня и образцам.${recentShapeBlock(recent)}\n\n${JSON.stringify(insight, null, 2)}`;
  if (previous) {
    msg += `\n\nПредыдущая версия поста:\n${previous.text}\n\nПравка автора канала: ${previous.feedback}\n\nПерепиши пост с учётом правки.`;
  }
  return msg;
}

